CREATE TABLE utilisateur (
    id_utilisateur BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom TEXT NOT NULL,
    prenom TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    ad TEXT,
    cp VARCHAR(10),
    ville TEXT,
    password_hash TEXT NOT NULL,
    role_utilisateur TEXT NOT NULL
);

CREATE TABLE type_anomalie (
    id_tp_ano BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lib_tp_ano TEXT NOT NULL UNIQUE
);

CREATE TABLE categorie_intervenant (
    id_categorie_intervenant BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lib_categorie_intervenant TEXT NOT NULL UNIQUE
);

CREATE TABLE intervenant (
    id_intervenant BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lib_int TEXT NOT NULL,
    ad_int TEXT,
    cp_int VARCHAR(10),
    email_int TEXT NOT NULL UNIQUE,
    ville_int TEXT,
    password_hash TEXT NOT NULL,
    id_categorie_intervenant BIGINT NOT NULL
        REFERENCES categorie_intervenant(id_categorie_intervenant)
);

CREATE TABLE secteur (
    id_secteur BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lib_secteur TEXT NOT NULL
);

CREATE TABLE itineraire_usuel (
    id_iti BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_ajout TIMESTAMPTZ NOT NULL DEFAULT now(),
    date_dernier_util TIMESTAMPTZ,
    rempli_par_user BOOLEAN NOT NULL DEFAULT FALSE,
    id_utilisateur BIGINT NOT NULL REFERENCES utilisateur(id_utilisateur)
);

CREATE TABLE point_gps (
    id_pt_gps BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lat_pt_gps NUMERIC(9, 6) NOT NULL
        CHECK (lat_pt_gps BETWEEN -90 AND 90),
    long_pt_gps NUMERIC(9, 6) NOT NULL
        CHECK (long_pt_gps BETWEEN -180 AND 180),
    id_iti BIGINT NOT NULL REFERENCES itineraire_usuel(id_iti)
);

CREATE TABLE anomalie (
    id_anomalie BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    latitude NUMERIC(9, 6) NOT NULL,
    longitude NUMERIC(9, 6) NOT NULL,
    nb_downvote INTEGER NOT NULL DEFAULT 0 CHECK (nb_downvote >= 0),
    nb_upvote INTEGER NOT NULL DEFAULT 0 CHECK (nb_upvote >= 0),
    date_ajout TIMESTAMPTZ NOT NULL DEFAULT now(),
    date_affectation TIMESTAMPTZ,
    id_tp_ano BIGINT NOT NULL REFERENCES type_anomalie(id_tp_ano),
    id_intervenant BIGINT REFERENCES intervenant(id_intervenant)
);

CREATE TABLE renseigner (
    id_utilisateur BIGINT NOT NULL REFERENCES utilisateur(id_utilisateur),
    id_anomalie BIGINT NOT NULL REFERENCES anomalie(id_anomalie),
    image_path TEXT,
    remarque TEXT,
    date_ajout TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (id_utilisateur, id_anomalie)
);

CREATE TABLE moderation_admin (
    id_moderation BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_utilisateur_admin BIGINT NOT NULL REFERENCES utilisateur(id_utilisateur),
    id_anomalie BIGINT NOT NULL REFERENCES anomalie(id_anomalie),
    date_inter TIMESTAMPTZ NOT NULL DEFAULT now(),
    remarque_inter TEXT
);

CREATE TABLE resoudre (
    id_resoudre BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_anomalie BIGINT NOT NULL REFERENCES anomalie(id_anomalie),
    id_intervenant BIGINT NOT NULL REFERENCES intervenant(id_intervenant),
    rq_resolution TEXT,
    date_resolution TIMESTAMPTZ NOT NULL DEFAULT now(),
    image_resolution TEXT
);

CREATE TABLE intervenir (
    id_intervenant BIGINT NOT NULL REFERENCES intervenant(id_intervenant),
    id_secteur BIGINT NOT NULL REFERENCES secteur(id_secteur),
    PRIMARY KEY (id_intervenant, id_secteur)
);

CREATE TABLE constituer (
    id_secteur BIGINT NOT NULL REFERENCES secteur(id_secteur),
    id_pt_gps BIGINT NOT NULL REFERENCES point_gps(id_pt_gps),
    PRIMARY KEY (id_secteur, id_pt_gps)
);